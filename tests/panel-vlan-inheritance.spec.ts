import { test, expect } from '@playwright/test';
import { defaultProject } from '../src/project';
import { defaultConfiguration } from '../src/configuration';

test('panel VLANs follow switch changes, bulk edits, reload and disconnection', async ({ page }) => {
  const project = defaultProject(defaultConfiguration(), 'metric');
  project.locations[0].layout.portVlans!['CAB-A01/PP-A04/18'] = 60;
  project.locations[0].layout.portVlans!['CAB-A01/PP-A04/24'] = 99;
  await page.addInitScript(project => {
    if (!localStorage.getItem('porttracker.project')) localStorage.setItem('porttracker.project', JSON.stringify(project));
  }, project);
  await page.goto('/');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  const panel = page.locator('[data-port="CAB-A01/PP-A04/18"]');
  const spare = page.locator('[data-port="CAB-A01/PP-A04/24"]');
  const switchPort = page.locator('[data-port="CAB-A02/SW-B01/18"]');
  const vlan = page.getByRole('combobox', { name: 'Port VLAN', exact: true });
  const cardVlan = page.getByRole('region', { name: 'Selected port details', exact: true }).locator('dl > div').filter({ hasText: /^VLAN/ }).locator('dd');
  await panel.press('Enter');
  await expect(page.getByRole('region', { name: 'Port VLAN assignment', exact: true })).toHaveCount(0);
  await expect(cardVlan).toContainText('30');
  await spare.press('Enter');await expect(cardVlan).toHaveText('Unassigned');
  await panel.press('Control+Enter');
  await expect(page.getByRole('region', { name: 'Bulk port VLAN assignment', exact: true })).toHaveCount(0);
  await switchPort.press('Enter');await expect(vlan).toBeEnabled();
  await vlan.selectOption('99');
  await panel.press('Enter');await expect(cardVlan).toContainText('99');
  await switchPort.press('Control+Enter');
  await page.getByRole('combobox', { name: 'VLAN for selected ports', exact: true }).selectOption('10');
  await page.getByRole('button', { name: 'Apply to 1 selected switch port', exact: true }).click();
  await expect(page.getByRole('table', { name: 'Selected ports', exact: true }).locator('tbody tr td:nth-child(2)')).toHaveText(['10', '10']);
  await page.reload();await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await panel.press('Enter');await expect(cardVlan).toContainText('10');
  await switchPort.press('Enter');await vlan.selectOption('');
  await panel.press('Enter');await expect(cardVlan).toHaveText('Unassigned');
  await switchPort.press('Enter');await vlan.selectOption('99');
  await panel.press('Enter');
  await page.getByRole('button', { name: 'View connection', exact: true }).click();
  const connectionVlan = page.locator('.connection-details > div').filter({ has: page.locator('dt', { hasText: /^VLAN$/ }) }).locator('dd');
  await expect(connectionVlan).toHaveText('99 — Servers');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await switchPort.press('Enter');await vlan.selectOption('');
  await page.getByRole('button', { name: 'View connection', exact: true }).click();
  await expect(connectionVlan).toHaveText('Unassigned');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await switchPort.press('Enter');await vlan.selectOption('99');
  await page.getByRole('button', { name: 'View connection', exact: true }).click();
  await page.getByRole('button', { name: 'Edit connection', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await panel.press('Enter');await expect(cardVlan).toHaveText('Unassigned');
  await switchPort.press('Enter');await expect(vlan).toHaveValue('99');
});
