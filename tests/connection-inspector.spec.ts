import { test, expect } from '@playwright/test';
import { defaultProject } from '../src/project';
import { defaultConfiguration } from '../src/configuration';

for (const mobile of [false, true]) test(`${mobile ? 'mobile' : 'desktop'} connections retain all details after browsing equipment`, async ({ page }) => {
  if (mobile) await page.setViewportSize({ width: 390, height: 844 });
  const project = defaultProject(defaultConfiguration(), 'metric');
  const switchName = 'bby01320n023-2';
  project.locations[0].layout.racks[1].equipment.find(e => e.id === 'SW-B01')!.label = switchName;
  project.locations[0].layout.racks[0].equipment.find(e => e.id === 'PP-A04')!.label = 'Floor patch panel';
  await page.addInitScript(project => {
    if (!localStorage.getItem('porttracker.project')) localStorage.setItem('porttracker.project', JSON.stringify(project));
  }, project);
  await page.goto('/');
  const panel = page.getByRole('tabpanel', { name: 'Connections', exact: true });
  await expect(panel.locator('.connection-details')).toContainText(`${switchName} / Port 18`);
  await expect(panel.locator('.connection-details')).toContainText('Floor patch panel / Port 18');
  await expect(panel.locator('.path-caption')).toContainText(`${switchName}:18`);
  await expect(panel.locator('.path-caption')).toContainText('Floor patch panel:18');
  const originalDetails = (await panel.locator('.connection-details').textContent())!;
  const originalEstimate = (await panel.locator('.estimate-summary').textContent())!;
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('combobox', { name: 'Manage rack', exact: true }).selectOption('CAB-A02');
  await page.getByRole('combobox', { name: 'Manage equipment', exact: true }).selectOption('PP-B20');
  await page.getByRole('tab', { name: 'Connections', exact: true }).click();
  await expect(panel.locator('.connection-id')).toContainText('CR-0018');
  await expect(panel.locator('.connection-details')).toHaveText(originalDetails);
  await expect(panel.locator('.estimate-summary')).toHaveText(originalEstimate);
  await expect(panel.getByRole('heading', { name: 'Path visualization' })).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Trace cable', exact: true })).toBeEnabled();
  await expect(panel.getByRole('button', { name: 'Edit connection', exact: true })).toBeEnabled();
  await expect(panel.getByRole('button', { name: 'Length calibration', exact: true })).toBeEnabled();
  await panel.locator('.length-breakdown summary').click();
  await expect(panel.locator('.length-breakdown')).toContainText('Service slack');
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('button', { name: 'Move equipment', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Bottom rack unit', exact: true }).fill('17');
  await page.getByRole('button', { name: 'Save equipment position', exact: true }).click();
  await page.getByRole('button', { name: 'Connections', exact: true }).click();
  await expect(panel.locator('.connection-id')).toContainText('CR-0018');
  if (!mobile) await expect(page.locator('.right-sidebar')).toHaveJSProperty('scrollTop', 0);
  await panel.getByRole('button', { name: 'Clear selection', exact: true }).click();
  await expect(panel.locator('.connection-details')).toHaveCount(0);
  await expect(panel.getByRole('button', { name: 'Edit connection', exact: true })).toBeDisabled();
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('button', { name: 'Manage ports', exact: true }).click();
  await expect(page.locator('.selected-port-info')).toContainText('PP-B20 / Port 1');
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('combobox', { name: 'Manage equipment', exact: true }).selectOption('SW-B01');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await expect(page.locator('.selected-port-info>strong')).toHaveText(`${switchName} / Port 1`);
  await expect(page.locator('.selected-port-info')).toContainText('Equipment ID: SW-B01');
  const positions = await page.locator('.port-browser').evaluate(panel => {
    const bottom = (selector: string) => panel.querySelector(selector)!.getBoundingClientRect().bottom;
    const top = (selector: string) => panel.querySelector(selector)!.getBoundingClientRect().top;
    return { summaryBottom: bottom('.selected-port-info'), pickerTop: top('.endpoint-picker'), gridBottom: bottom('.port-grid'), controlsTop: top('.selected-port-controls') };
  });
  expect(positions.summaryBottom).toBeLessThan(positions.pickerTop);
  expect(positions.gridBottom).toBeLessThan(positions.controlsTop);
  await page.getByRole('checkbox', { name: 'Select multiple ports', exact: true }).check();
  await expect(page.locator('.selected-port-info')).toHaveCount(0);
  await page.reload();
  await expect(page.locator('.connection-details')).toContainText(`${switchName} / Port 18`);
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('porttracker.project')!));
  expect(saved.locations[0].layout.cables).toEqual(project.locations[0].layout.cables);
});
