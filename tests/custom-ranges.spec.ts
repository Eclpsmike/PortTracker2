import { seedFacilityLocations } from './facility-location-helpers';
import { test, expect, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import type { Project } from '../src/project';
const saved = (page: Page): Promise<Project> => page.evaluate(() => JSON.parse(localStorage.getItem('porttracker.project')!));
async function openRange(page: Page) { await page.getByRole('tab', { name: 'Equipment', exact: true }).click(); await page.locator('.equipment-manager summary').filter({ hasText: /^Port numbering/ }).click(); }
async function setRange(page: Page, start: string) {
  await openRange(page);
  await page.getByRole('spinbutton', { name: 'Equipment starting port number', exact: true }).fill(start);
  await page.getByRole('button', { name: 'Save port range', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
}

test.beforeEach(async ({ page }) => { await seedFacilityLocations(page, ["West wing"]); });

test('installed patch panel ranges preserve selected sockets, cables, bulk data, zoom and backups', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  const zoom = await page.locator('.zoom-control span').textContent();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('button', { name: 'Port 18, connected', exact: true }).click();
  await page.getByRole('combobox', { name: 'Facility location', exact: true }).selectOption('West wing');
  await page.getByRole('combobox', { name: 'Port VLAN', exact: true }).selectOption('99');
  await setRange(page, '25');
  await expect(page.locator('.selected-port-info')).toContainText('PP-A04 / Port 42');
  await expect(page.getByRole('combobox', { name: 'Facility location', exact: true })).toHaveValue('West wing');
  await expect(page.getByRole('combobox', { name: 'Port VLAN', exact: true })).toHaveValue('99');
  await expect(page.locator('.port-grid button')).toHaveCount(24);
  await expect(page.getByRole('button', { name: 'Port 25, available', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Port 48, available', exact: true })).toBeVisible();
  await expect(page.locator('.zoom-control span')).toHaveText(zoom!);
  await page.getByRole('checkbox', { name: 'Select multiple ports', exact: true }).check();
  await page.getByRole('button', { name: 'Select all 24 ports', exact: true }).click();
  await page.getByRole('combobox', { name: 'VLAN for selected ports', exact: true }).selectOption('60');
  await page.getByRole('button', { name: 'Apply to 24 selected ports', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Select multiple ports', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Port 42, connected', exact: true }).click();
  await setRange(page, '26'); // Overlapping ranges must not overwrite existing port data.
  await expect(page.locator('.selected-port-info')).toContainText('PP-A04 / Port 43');
  const project = await saved(page);
  expect(project.locations[0].layout.cables.find(c => c.id === 'CR-0018')!.from.port).toBe(43);
  expect(project.locations[0].layout.portDetails!['CAB-A01/PP-A04/43'].facilityLocation).toBe('West wing');
  for (let n = 26; n <= 49; n++) expect(project.locations[0].layout.portVlans![`CAB-A01/PP-A04/${n}`]).toBe(60);
  expect(project.locations[0].layout.portVlans!['CAB-A01/PP-A04/25']).toBeUndefined();
  await page.setViewportSize({ width: 390, height: 844 });
  await openRange(page);
  await page.getByRole('spinbutton', { name: 'Equipment starting port number', exact: true }).fill('-1');
  await expect(page.getByRole('button', { name: 'Save port range', exact: true })).toBeDisabled();
  await page.getByRole('spinbutton', { name: 'Equipment starting port number', exact: true }).fill('26');
  await page.locator('.equipment-manager details').filter({ has: page.getByRole('spinbutton', { name: 'Equipment starting port number', exact: true }) }).screenshot({ path: 'artifacts/custom-range-mobile.png' });
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export', exact: true }).click();
  const backup = await readFile((await (await download).path())!);
  await page.reload();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('combobox', { name: 'Browse equipment', exact: true }).selectOption('PP-A04');
  await page.getByRole('button', { name: 'Port 43, connected', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Facility location', exact: true })).toHaveValue('West wing');
  await openRange(page);
  await page.getByRole('button', { name: 'Use template range (1–24)', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await expect(page.locator('.selected-port-info')).toContainText('PP-A04 / Port 18');
  await page.goto('/#/locations');
  await page.getByLabel('Project JSON file').setInputFiles({ name: 'ranges.json', mimeType: 'application/json', buffer: backup });
  await page.getByRole('button', { name: 'Replace with imported project', exact: true }).click();
  await page.getByRole('button', { name: 'Open IDF-01', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('combobox', { name: 'Browse equipment', exact: true }).selectOption('PP-A04');
  await expect(page.getByRole('button', { name: 'Port 43, connected', exact: true })).toBeVisible();
  await expect(page.locator('.zoom-control span')).toHaveText(zoom!);
  expect(errors).toEqual([]);
});

test('template range previews, placement inheritance and device overrides work together', async ({ page }) => {
  await page.goto('/#/configuration/templates');
  await page.getByRole('button', { name: 'Import template', exact: true }).click();
  await page.getByLabel('Device definition YAML').setInputFiles('public/equipment/netbox/24-port-copper-patch-panel.yaml');
  await page.getByLabel('Front equipment image', { exact: true }).setInputFiles('public/equipment/netbox/generic-24-port-copper-patch-panel.front.png');
  await page.getByLabel('Template name', { exact: true }).fill('Range panel');
  await page.getByRole('button', { name: 'Continue to port mapping', exact: true }).click();
  const start = page.getByRole('spinbutton', { name: 'Starting port number', exact: true });
  await start.fill('25');
  await expect(page.getByLabel('Mapped port', { exact: true }).locator('option').first()).toHaveText('25 — Port 1 (unmapped)');
  await page.getByText('Start with a regular grid', { exact: true }).click();
  await page.getByRole('button', { name: 'Generate port grid', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select mapped port 48', exact: true })).toBeVisible();
  const review = page.getByLabel('I checked every socket position and numbered interface against the image.');
  await start.fill('999977'); await review.check();
  await expect(page.getByRole('button', { name: 'Save template', exact: true })).toBeDisabled();
  await start.fill('25'); await review.check();
  await page.getByRole('button', { name: 'Save template', exact: true }).click();
  await page.getByRole('button', { name: 'Place Range panel in rack', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Ports 25–48');
  await page.getByRole('textbox', { name: 'Equipment ID', exact: true }).fill('PP-RANGE');
  await page.getByRole('button', { name: 'Place equipment', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Equipment', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Manage ports', exact: true }).click();
  await expect(page.locator('.selected-port-info strong')).toHaveText('PP-001 / Port 25');
  await expect(page.locator('.selected-port-info')).toContainText('Equipment ID: PP-RANGE');
  await setRange(page, '49');
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await page.getByRole('link', { name: 'Equipment templates', exact: true }).click();
  await page.getByRole('button', { name: 'Edit template Range panel', exact: true }).click();
  await start.fill('73'); await review.check();
  await page.getByRole('button', { name: 'Save template', exact: true }).click();
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await expect(page.locator('.selected-port-info strong')).toHaveText('PP-001 / Port 49');
  await openRange(page);
  await page.getByRole('button', { name: 'Use template range (73–96)', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await expect(page.locator('.selected-port-info strong')).toHaveText('PP-001 / Port 73');
  await expect(page.getByRole('button', { name: 'Port 96, available', exact: true })).toBeVisible();
});
