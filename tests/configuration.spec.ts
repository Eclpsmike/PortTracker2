import { test, expect } from '@playwright/test';

test('VLAN CRUD propagates to connections, colors, filters, persistence, and navigation', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'VLAN list', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Remove VLAN 30', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Edit VLAN 30', exact: true }).click();
  await expect(page.getByRole('spinbutton', { name: 'VLAN ID' })).toBeDisabled();
  await page.getByRole('textbox', { name: 'VLAN name' }).fill('Telephony');
  await page.getByLabel('Overlay color', { exact: true }).fill('#cc2255');
  await page.getByRole('button', { name: 'Save VLAN', exact: true }).click();
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await expect(page.locator('.connection-details')).toContainText('30 — Telephony');
  await expect(page.locator('.cable-group.selected path').nth(1)).toHaveAttribute('stroke', '#cc2255');
  await expect(page.locator('.path-diagram > path').nth(1)).toHaveAttribute('stroke', '#cc2255');
  await expect(page.locator('.vlan-list')).toContainText('Telephony');
  await page.getByRole('button', { name: 'Edit connection', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Logical VLAN' }).locator('option:checked')).toHaveText('30 · Telephony');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();

  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await page.getByRole('button', { name: 'Add VLAN', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'VLAN ID' }).fill('30');
  await page.getByRole('textbox', { name: 'VLAN name' }).fill('Lab');
  await page.getByRole('button', { name: 'Save VLAN', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('already exists');
  await page.getByRole('spinbutton', { name: 'VLAN ID' }).fill('200');
  await page.getByRole('button', { name: 'Save VLAN', exact: true }).click();
  await page.getByRole('textbox', { name: 'Search VLANs' }).fill('Lab');
  await expect(page.locator('.configuration-table tbody tr')).toHaveCount(1);
  await expect(page.locator('.configuration-table')).toContainText('200');
  await page.getByRole('textbox', { name: 'Search VLANs' }).fill('');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'VLAN list', exact: true })).toBeVisible();
  await expect(page.locator('.configuration-table')).toContainText('Telephony');
  await expect(page.getByRole('button', { name: 'Edit VLAN 200', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await page.getByRole('button', { name: 'Add connection', exact: true }).click();
  await page.getByRole('combobox', { name: 'Logical VLAN' }).selectOption('200');
  await page.getByRole('button', { name: 'Create connection', exact: true }).click();
  await expect(page.locator('.connection-details')).toContainText('200 — Lab');
  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove VLAN 200', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Remove VLAN 99', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit VLAN 99', exact: true })).toHaveCount(0);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'artifacts/configuration-vlans.png' });
  await page.goBack();
  await expect(page.locator('.rack-viewport')).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove VLAN 200', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Remove VLAN 200', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Edit VLAN 200', exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('cable stock supports inches, live recommendations, duplicate checks, editing and removal', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('link', { name: 'STOCK LENGTH', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Cable stock', exact: true })).toBeVisible();
  await page.locator('.configuration-content').getByRole('combobox', { name: 'Length units', exact: true }).selectOption('imperial');
  await page.getByRole('button', { name: 'Add stock length', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Cable length (in)' }).fill('0');
  await page.getByRole('button', { name: 'Save stock length', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('greater than zero');
  await page.getByRole('spinbutton', { name: 'Cable length (in)' }).fill('39.37008');
  await page.getByRole('button', { name: 'Save stock length', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('already in stock');
  await page.getByRole('spinbutton', { name: 'Cable length (in)' }).fill('144');
  await page.getByRole('button', { name: 'Save stock length', exact: true }).click();
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await expect(page.locator('.estimate-summary strong').nth(1)).toHaveText('12.00 ft');
  await page.getByRole('button', { name: 'Length calibration', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('144.00');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('link', { name: 'STOCK LENGTH', exact: true }).click();
  await page.getByRole('button', { name: 'Edit stock length 144.00 in', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Cable length (in)' }).fill('180');
  await page.getByRole('button', { name: 'Save stock length', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Edit stock length 180.00 in', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await expect(page.locator('.estimate-summary strong').nth(1)).toHaveText('15.00 ft');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  await expect(page.locator('.estimate-summary strong').nth(1)).toHaveText('15.00 ft');
  await page.getByRole('link', { name: 'STOCK LENGTH', exact: true }).click();
  await page.locator('.configuration-content').getByRole('combobox', { name: 'Length units', exact: true }).selectOption('metric');
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'artifacts/configuration-stock.png' });
  await page.getByRole('button', { name: 'Remove stock length 4.57 m', exact: true }).click();
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await expect(page.locator('.estimate-summary strong').nth(1)).toHaveText('5.00 m');
  await page.getByRole('link', { name: 'STOCK LENGTH', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Cable stock', exact: true })).toBeVisible();
  const removeButtons = page.getByRole('button', { name: /^Remove stock length/ });
  await expect(removeButtons.first()).toBeVisible();
  for (let remaining = await removeButtons.count(); remaining > 0; remaining--) {
    await removeButtons.first().click();
    await expect(removeButtons).toHaveCount(remaining - 1);
  }
  await expect(page.getByRole('table', { name: 'Available cable lengths', exact: true }).locator('.config-empty')).toContainText('No stocked lengths');
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await expect(page.locator('.estimate-summary strong').nth(1)).toHaveText('No stock match');
  await page.reload();
  await expect(page.locator('.estimate-summary strong').nth(1)).toHaveText('No stock match');
});

test('configuration pages fit mobile and recover from invalid or unavailable storage', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.addInitScript(() => { localStorage.removeItem('porttracker.project'); localStorage.setItem('porttracker.configuration', '{broken'); });
  await page.goto('/#/configuration/vlans');
  await expect(page.getByRole('status')).toContainText('could not be read');
  await expect(page.getByRole('heading', { name: 'VLAN list', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'artifacts/configuration-mobile.png', fullPage: true });
  await page.getByRole('link', { name: 'Cable stock', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Storage denied'); }; });
  await page.getByRole('button', { name: 'Add stock length', exact: true }).click();
  await page.getByRole('spinbutton', { name: 'Cable length (m)' }).fill('4');
  await page.getByRole('button', { name: 'Save stock length', exact: true }).click();
  await expect(page.locator('.configuration-warning')).toContainText('Browser storage is unavailable');
  await expect(page.getByRole('button', { name: 'Edit stock length 4.00 m', exact: true })).toBeVisible();
});
