test('SVG selection, JSON export, and static graphics fallback', async ({ page, browser }) => {
  await page.goto('/');
  await page.locator('[data-port="CAB-A01/PP-A01/24"]').click();
  await expect(page.locator('.selected-port-info')).toContainText('PP-A01 / Port 24');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('porttracker-project.json');
  const context = await browser.newContext({ javaScriptEnabled: false });
  const staticPage = await context.newPage();
  await staticPage.goto(new URL('/', page.url()).href);
  const image = staticPage.getByRole('img', { name: 'Two 42U network racks with patch panels, switches, and routed cables' });
  await expect(image).toBeVisible();
  expect(await image.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
  await context.close();
});

async function exportedDemo(page: Page) {
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const project = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  return { ...project, ...project.locations.find((l: { id: string }) => l.id === project.activeLocationId) };
}

test('standard cable estimates use feet while calibration uses inches and preserves precision', async ({ page }) => {
  await page.goto('/');
  const original = await exportedDemo(page);
  const selector = page.getByRole('combobox', { name: 'Length units', exact: true });
  await expect(selector).toHaveValue('metric');
  await expect(page.locator('.estimate-summary strong').first()).toHaveText('3.57 m');
  await selector.selectOption('imperial');
  await expect(page.locator('.estimate-summary strong').first()).toHaveText('11.73 ft');
  await expect(page.locator('.estimate-summary strong').nth(1)).toHaveText('16.40 ft');
  await expect(selector.locator('option:checked')).toHaveText('Standard / US (ft)');
  await page.locator('.length-breakdown summary').click();
  await expect(page.locator('.length-breakdown')).toContainText('1.64 ft');
  await page.getByRole('button', { name: 'Length calibration', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('spinbutton', { name: 'Service slack' })).toHaveValue('19.685039');
  await expect(dialog.getByRole('combobox', { name: 'Length units' }).locator('option:checked')).toHaveText('Standard / US (in)');
  await expect(dialog).toContainText('Rack U: 1.75 in');
  for (let n = 0; n < 3; n++) {
    await dialog.getByRole('combobox', { name: 'Length units' }).selectOption('metric');
    await dialog.getByRole('combobox', { name: 'Length units' }).selectOption('imperial');
  }
  await dialog.getByRole('button', { name: 'Apply values' }).click();
  const unchanged = await exportedDemo(page);
  expect(unchanged.calibration).toEqual({ ...original.calibration, equipmentWidthM: 19 * .0254, verticalManagerWidthM: 0, managerOverlapM: 0 });
  expect(unchanged.layout.racks).toEqual(original.layout.racks);
  expect(unchanged.preferences.lengthUnit).toBe('imperial');

  await page.getByRole('button', { name: 'Length calibration', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Length units' }).selectOption('metric');
  await dialog.getByRole('spinbutton', { name: 'Service slack' }).fill('2');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(selector).toHaveValue('imperial');
  await expect(page.locator('.estimate-summary strong').first()).toHaveText('11.72 ft');

  await page.getByRole('button', { name: 'Length calibration', exact: true }).click();
  await page.getByRole('dialog').getByRole('spinbutton', { name: 'Service slack' }).fill('36');
  await page.getByRole('button', { name: 'Apply values' }).click();
  await expect(page.locator('.estimate-summary strong').first()).toHaveText('13.08 ft');
  const edited = await exportedDemo(page);
  expect(edited.calibration.slackM).toBeCloseTo(.9144, 12);
  await selector.selectOption('metric');
  await expect(page.locator('.estimate-summary strong').first()).toHaveText('3.99 m');
  await selector.selectOption('imperial');
  await page.reload();
  await expect(selector).toHaveValue('imperial');
  await expect(page.locator('.estimate-summary strong').first()).toHaveText('13.08 ft');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  await expect(selector).toHaveValue('imperial');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
