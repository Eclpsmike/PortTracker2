import { test, expect, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import type { Project } from '../src/project';

async function savedProject(page: Page): Promise<Project> {
  return page.evaluate(() => JSON.parse(localStorage.getItem('porttracker.project')!));
}
async function addLocation(page: Page, name: string, copy = false) {
  await page.getByRole('link', { name: 'Distribution Frames', exact: true }).click();
  await page.getByRole('button', { name: 'Add distribution frame', exact: true }).click();
  await page.getByRole('textbox', { name: 'Distribution frame name', exact: true }).fill(name);
  await page.getByRole('combobox', { name: 'Distribution frame type' }).selectOption('MDF');
  await page.getByRole('textbox', { name: 'Floor', exact: true }).fill('1');
  await page.getByRole('textbox', { name: 'Room', exact: true }).fill('101');
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Main distribution room');
  if (copy) await page.getByRole('combobox', { name: 'Starting layout' }).selectOption('idf-01');
  await page.getByRole('button', { name: 'Save distribution frame', exact: true }).click();
}

test('MDF/IDF creation, rename, switching and reload preserve independent layouts and port assignments', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await addLocation(page, 'MDF-01', true);
  await expect(page.getByRole('article', { name: 'MDF-01 distribution frame', exact: true })).toContainText('2 racks · 0 connections · 0 VLAN-assigned ports');
  await page.getByRole('button', { name: 'Open MDF-01', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'MDF-01', exact: true })).toBeVisible();
  await expect(page.locator('.rack-port')).toHaveCount(1440);
  await expect(page.locator('.cable-group')).toHaveCount(0);
  const originalId = (await savedProject(page)).activeLocationId;
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Select multiple ports' }).check();
  await page.getByRole('button', { name: 'Port 23, available', exact: true }).click();
  await page.getByRole('button', { name: 'Port 24, available', exact: true }).click();
  await page.getByRole('combobox', { name: 'VLAN for selected ports' }).selectOption('99');
  await page.getByRole('button', { name: 'Apply to 2 selected ports' }).click();
  await page.getByRole('combobox', { name: 'Active distribution frame' }).selectOption('idf-01');
  await expect(page.locator('.cable-group')).toHaveCount(32);
  await expect(page.locator('[data-port="CAB-A01/PP-A04/24"]')).not.toHaveAttribute('data-vlan');
  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove VLAN 99', exact: true })).toBeDisabled();
  await page.getByRole('link', { name: 'Distribution Frames', exact: true }).click();
  await page.getByRole('button', { name: 'Edit MDF-01', exact: true }).click();
  await page.getByRole('textbox', { name: 'Distribution frame name', exact: true }).fill('Main MDF');
  await page.getByRole('combobox', { name: 'Building', exact: true }).fill('Building B');
  await page.getByRole('button', { name: 'Save distribution frame', exact: true }).click();
  await page.getByRole('button', { name: 'Open Main MDF', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Active distribution frame' })).toHaveValue(originalId);
  await expect(page.locator('[data-port="CAB-A01/PP-A04/24"]')).toHaveAttribute('data-vlan', '99');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Main MDF', exact: true })).toBeVisible();
  await expect(page.locator('[data-port="CAB-A01/PP-A04/24"]')).toHaveAttribute('data-vlan', '99');
  await page.getByRole('button', { name: 'Add connection', exact: true }).click();
  await page.getByRole('button', { name: 'Create connection', exact: true }).click();
  await page.reload();
  await expect(page.locator('.cable-group')).toHaveCount(1);
  await expect(page.locator('.connection-id')).toContainText('NEW-0001');
  await page.getByRole('link', { name: 'Distribution Frames', exact: true }).click();
  await page.screenshot({ path: 'artifacts/locations-desktop.png' });
  expect((await savedProject(page)).locations.find(l => l.id === originalId)?.id).toBe(originalId);
  expect(errors).toEqual([]);
});

