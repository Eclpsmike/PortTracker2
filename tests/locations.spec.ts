test('project export/import previews replacement, rejects corrupt files and restores all locations', async ({ page }) => {
  await page.goto('/');
  await addLocation(page, 'MDF-Backup', true);
  await page.getByRole('textbox', { name: 'Site name', exact: true }).fill('Campus');
  await page.getByRole('button', { name: 'Save site name', exact: true }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export project', exact: true }).click();
  const download = await pending;
  expect(download.suggestedFilename()).toBe('porttracker-project.json');
  const backup = await readFile((await download.path())!);
  const original = JSON.parse(backup.toString()) as Project;
  await page.getByRole('textbox', { name: 'Site name', exact: true }).fill('Changed');
  await page.getByRole('button', { name: 'Save site name', exact: true }).click();
  await page.getByLabel('Project JSON file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{broken') });
  await expect(page.getByRole('alert')).toContainText('not valid JSON');
  expect((await savedProject(page)).siteName).toBe('Changed');
  await page.getByLabel('Project JSON file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: backup });
  await expect(page.getByRole('region', { name: 'Import preview' })).toContainText('2 distribution frames');
  expect((await savedProject(page)).siteName).toBe('Changed');
  await page.getByRole('button', { name: 'Cancel import', exact: true }).click();
  expect((await savedProject(page)).siteName).toBe('Changed');
  await page.getByLabel('Project JSON file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: backup });
  await page.getByRole('button', { name: 'Replace with imported project', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Site name', exact: true })).toHaveValue('Campus');
  expect(await savedProject(page)).toEqual({ ...original, configuration: { ...original.configuration, facilityLocations: original.configuration.facilityLocations ?? [] } });
  await page.reload();
  await expect(page.getByRole('article', { name: 'MDF-Backup distribution frame', exact: true })).toBeVisible();
});

test('corrupt saved project is preserved until explicit recovery; failed saves remain exportable', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('porttracker.project', '{broken'));
  await page.goto('/');
  await expect(page.locator('.project-storage-notice')).toContainText('has not been replaced');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('button', { name: 'Port 24, available', exact: true }).click();
  await page.getByRole('combobox', { name: 'Port VLAN', exact: true }).selectOption('99');
  expect(await page.evaluate(() => localStorage.getItem('porttracker.project'))).toBe('{broken');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Start new project', exact: true }).click();
  await expect(page.locator('.project-storage-notice')).toHaveCount(0);
  expect((await savedProject(page)).locations[0].layout.portVlans!['CAB-A01/PP-A04/24']).toBe(99);
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new Error('Storage denied'); }; });
  await page.getByRole('combobox', { name: 'Port VLAN', exact: true }).selectOption('60');
  await expect(page.locator('.project-storage-notice')).toContainText('in memory only');
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const download = await pending;
  const exported = JSON.parse(await readFile((await download.path())!, 'utf8')) as Project;
  expect(exported.locations[0].layout.portVlans!['CAB-A01/PP-A04/24']).toBe(60);
  expect((await savedProject(page)).locations[0].layout.portVlans!['CAB-A01/PP-A04/24']).toBe(99);
});
