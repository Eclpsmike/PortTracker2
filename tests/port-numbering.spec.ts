import { seedFacilityLocations } from './facility-location-helpers';
import { test, expect, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import type { Project } from '../src/project';
import { EQUIPMENT_TEMPLATES } from '../src/equipmentTemplates';
async function saved(page: Page): Promise<Project> { return page.evaluate(() => JSON.parse(localStorage.getItem('porttracker.project')!)); }
async function addZero(page: Page, template: string, id: string) {
  const source = EQUIPMENT_TEMPLATES.find(t => t.id === template)!;
  const image = await readFile(`public${source.imageSrc}`);
  await page.evaluate(t => { const p = JSON.parse(localStorage.getItem('porttracker.project')!); p.templates = [t]; localStorage.setItem('porttracker.project', JSON.stringify(p)); }, { ...source, id: 'custom-zero', name: 'Zero template', portStart: 0, imageSrc: `data:image/png;base64,${image.toString('base64')}`, source: { manufacturer: 'Test', model: 'Zero', filename: 'zero.yaml' }, ports: source.ports.map((p, i) => ({ ...p, name: `Port ${i}` })) });
  await page.reload();
  await page.getByRole('button', { name: 'Add equipment', exact: true }).click();
  const checkbox = page.getByRole('spinbutton', { name: 'Starting port number', exact: true });
  await expect(checkbox).toHaveCount(0);
  await page.getByRole('combobox', { name: 'Equipment template', exact: true }).selectOption('custom-zero');
  await expect(page.getByRole('dialog')).toContainText(`Ports 0–${source.portCount - 1}`);
  await page.getByRole('textbox', { name: 'Equipment ID', exact: true }).fill(id);
  await page.getByRole('textbox', { name: 'Equipment label', exact: true }).fill(id);
  await page.getByRole('spinbutton', { name: 'Bottom rack unit', exact: true }).fill('17');
  await page.getByRole('button', { name: 'Place equipment', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Equipment', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Manage ports', exact: true }).click();
}

