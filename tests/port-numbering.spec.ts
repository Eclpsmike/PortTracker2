test('zero-based switch ports work in bulk selection, cables, moves and backup restoration', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await addZero(page, 'netbox-ubiquiti-us-48', 'SW-ZERO');
  await expect(page.locator('.selected-port-info')).toContainText('SW-ZERO / Port 0');
  await expect(page.locator('.port-grid button')).toHaveCount(48);
  await expect(page.getByRole('button', { name: 'Port 47, available', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Port 48, available', exact: true })).toHaveCount(0);
  await page.locator('[data-port="CAB-A01/SW-ZERO/0"]').click();
  await expect(page.locator('[data-grid-port="CAB-A01/SW-ZERO/0"]')).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('checkbox', { name: 'Select multiple ports' }).check();
  await page.getByRole('button', { name: 'Port 0, available', exact: true }).click();
  await page.getByRole('button', { name: 'Port 2, available', exact: true }).click({ modifiers: ['Shift'] });
  await expect(page.locator('.bulk-port-count')).toHaveText('3 ports selected');
  await page.getByRole('combobox', { name: 'VLAN for selected ports', exact: true }).selectOption('60');
  await page.getByRole('button', { name: 'Apply to 3 selected ports', exact: true }).click();
  await page.getByRole('button', { name: 'Select all 48 ports', exact: true }).click();
  await page.getByRole('combobox', { name: 'VLAN for selected ports', exact: true }).selectOption('99');
  await page.getByRole('button', { name: 'Apply to 48 selected ports', exact: true }).click();
  await expect(page.locator('.port-grid [data-vlan="99"]')).toHaveCount(48);
  await page.getByRole('checkbox', { name: 'Select multiple ports' }).uncheck();
  await page.getByRole('button', { name: 'Port 0, available', exact: true }).click();
  await page.getByRole('button', { name: 'Add connection', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'From port', exact: true })).toHaveValue('0');
  await page.getByRole('combobox', { name: 'From equipment', exact: true }).selectOption('SW-A01');
  await expect(page.getByRole('combobox', { name: 'From port', exact: true })).toHaveValue('1');
  await page.getByRole('combobox', { name: 'From equipment', exact: true }).selectOption('SW-ZERO');
  await expect(page.getByRole('combobox', { name: 'From port', exact: true })).toHaveValue('0');
  await page.getByRole('button', { name: 'Create connection', exact: true }).click();
  await expect(page.locator('.connection-details')).toContainText('SW-ZERO / Port 0');
  const start = await page.locator('.cable-group.selected > path').first().evaluate((p: SVGPathElement) => { const point = p.getPointAtLength(0); return { x: point.x, y: point.y }; });
  const socket = await page.locator('[data-port="CAB-A01/SW-ZERO/0"] .port-hit').evaluate((r: SVGRectElement) => ({ x: r.x.baseVal.value + r.width.baseVal.value / 2, y: r.y.baseVal.value + r.height.baseVal.value / 2 }));
  expect(start.x).toBeCloseTo(socket.x, 3); expect(start.y).toBeCloseTo(socket.y, 3);
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('button', { name: 'Move equipment', exact: true }).click();
  await page.getByRole('combobox', { name: 'Destination rack', exact: true }).selectOption('CAB-A02');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button', { name: 'Save equipment position', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Equipment', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Manage ports', exact: true }).click();
  await expect(page.locator('.selected-port-info')).toContainText('SW-ZERO / Port 0');
  const backupPromise = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export', exact: true }).click();
  const backup = await readFile((await (await backupPromise).path())!);
  const project = JSON.parse(backup.toString()) as Project;
  expect(project.locations[0].layout.racks[1].equipment.find(e => e.id === 'SW-ZERO')!.portStart).toBe(0);
  expect(project.locations[0].layout.cables.find(c => c.id === 'CBL-0001')!.from.port).toBe(0);
  expect(project.locations[0].layout.portVlans!['CAB-A02/SW-ZERO/0']).toBe(99);
  expect(project.locations[0].layout.portVlans!['CAB-A02/SW-ZERO/48']).toBeUndefined();
  await page.reload();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('combobox', { name: 'Browse rack', exact: true }).selectOption('CAB-A02');
  await page.getByRole('combobox', { name: 'Browse equipment', exact: true }).selectOption('SW-ZERO');
  await expect(page.locator('.selected-port-info')).toContainText('SW-ZERO / Port 0');
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('link', { name: 'Distribution Frames', exact: true }).click();
  await page.getByLabel('Project JSON file').setInputFiles({ name: 'zero.json', mimeType: 'application/json', buffer: backup });
  await page.getByRole('button', { name: 'Replace with imported project', exact: true }).click();
  await page.getByRole('button', { name: 'Open IDF-01', exact: true }).click();
  await expect(page.locator('[data-port="CAB-A02/SW-ZERO/0"]')).toHaveAttribute('data-vlan', '99');
  expect(errors).toEqual([]);
});

