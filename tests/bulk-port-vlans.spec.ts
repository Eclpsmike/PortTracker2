import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('bulk port selection supports toggles, ranges and independent VLAN assignment', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Select multiple ports' }).check();
  const gridPort = (n: number) => page.locator(`[data-grid-port="CAB-A01/PP-A04/${n}"]`);
  const apply = page.getByRole('button', { name: /^Apply to \d+ selected ports$/ });
  await expect(apply).toBeDisabled();
  await gridPort(18).click();
  await gridPort(21).click({ modifiers: ['Shift'] });
  await expect(page.locator('.bulk-port-count')).toHaveText('4 ports selected');
  await gridPort(20).click();
  await expect(gridPort(20)).toHaveAttribute('aria-pressed', 'false');
  await expect(page.locator('.bulk-port-count')).toHaveText('3 ports selected');
  await expect(page.locator('.bulk-current-vlan')).toHaveText('Current VLANs: mixed assignments');
  for (const n of [18, 19, 21]) await expect(page.locator(`[data-port="CAB-A01/PP-A04/${n}"]`)).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('combobox', { name: 'VLAN for selected ports' }).selectOption('99');
  await expect(gridPort(19)).not.toHaveAttribute('data-vlan');
  await apply.click();
  for (const n of [18, 19, 21]) await expect(gridPort(n)).toHaveAttribute('data-vlan', '99');
  await expect(gridPort(20)).not.toHaveAttribute('data-vlan');
  await expect(page.locator('.bulk-current-vlan')).toContainText('Current VLAN: 99');
  await expect(page.locator('.cable-group')).toHaveCount(32);
  const pendingDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const download = await pendingDownload;
  const saved = JSON.parse(await readFile((await download.path())!, 'utf8'));
  expect(saved.locations.find((l: { id: string }) => l.id === saved.activeLocationId).layout.cables.find((c: { id: string }) => c.id === 'CR-0018').vlan).toBe(30);
  for (const n of [18, 19, 21]) expect(saved.locations.find((l: { id: string }) => l.id === saved.activeLocationId).layout.portVlans[`CAB-A01/PP-A04/${n}`]).toBe(99);
  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove VLAN 99', exact: true })).toBeDisabled();
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await expect(page.locator('.bulk-port-count')).toHaveText('3 ports selected');
  await page.getByRole('combobox', { name: 'VLAN for selected ports' }).selectOption('clear');
  await apply.click();
  for (const n of [18, 19, 21]) await expect(gridPort(n)).not.toHaveAttribute('data-vlan');
  await expect(page.locator('.bulk-current-vlan')).toHaveText('Current VLAN: unassigned');
  await page.getByRole('button', { name: 'Select all 24 ports' }).click();
  await expect(page.locator('.port-grid [aria-pressed="true"]')).toHaveCount(24);
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click();
  await expect(apply).toBeDisabled();
  await page.getByRole('checkbox', { name: 'Select multiple ports' }).uncheck();
  await gridPort(24).click();
  await expect(page.getByRole('combobox', { name: 'Port VLAN', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('mobile bulk assignment supports all 48 switch ports and clears selection on device changes and reset', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Select multiple ports' }).check();
  await page.getByRole('combobox', { name: 'Browse equipment' }).selectOption('SW-A01');
  await page.getByRole('button', { name: 'Select all 48 ports' }).click();
  await expect(page.locator('.port-grid [aria-pressed="true"]')).toHaveCount(48);
  await page.getByRole('combobox', { name: 'VLAN for selected ports' }).selectOption('60');
  await page.getByRole('button', { name: 'Apply to 48 selected ports' }).click();
  await expect(page.locator('.port-grid [data-vlan="60"]')).toHaveCount(48);
  await page.getByRole('combobox', { name: 'Browse equipment' }).selectOption('PP-A01');
  await expect(page.locator('.bulk-port-count')).toHaveText('0 ports selected');
  await expect(page.getByRole('button', { name: 'Apply to 0 selected ports' })).toBeDisabled();
  await expect(page.getByRole('combobox', { name: 'VLAN for selected ports' })).toHaveValue('');
  await page.getByRole('button', { name: 'Port 24, available', exact: true }).click();
  await page.getByRole('combobox', { name: 'Browse rack' }).selectOption('CAB-A02');
  await expect(page.locator('.bulk-port-count')).toHaveText('0 ports selected');
  await page.getByRole('button', { name: 'Port 24, available', exact: true }).focus();
  await page.keyboard.press('Space');
  await expect(page.locator('.bulk-port-count')).toHaveText('1 port selected');
  await page.getByRole('combobox', { name: 'VLAN for selected ports' }).selectOption('99');
  await page.getByRole('button', { name: 'Apply to 1 selected port' }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/bulk-port-vlans-mobile.png', fullPage: true });
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Select multiple ports' })).not.toBeChecked();
  await page.getByRole('checkbox', { name: 'Select multiple ports' }).check();
  await expect(page.locator('.bulk-port-count')).toHaveText('0 ports selected');
});
