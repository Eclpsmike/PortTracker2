test('invalid definitions, unsupported images, unmapped and overlapping sockets cannot be saved', async ({ page }) => {
  await openImporter(page);
  await page.getByLabel('Device definition YAML').setInputFiles({ name: 'bad.yaml', mimeType: 'text/yaml', buffer: Buffer.from('model: [') });
  await expect(page.getByRole('alert')).toContainText('Cannot read YAML');
  await expect(page.getByRole('button', { name: 'Continue to port mapping' })).toBeDisabled();
  await page.getByLabel('Equipment image', { exact: true }).setInputFiles({ name: 'bad.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') });
  await expect(page.getByRole('alert')).toContainText('SVG files are not supported');
  await uploadPanel(page);
  await page.getByLabel('Grid socket width (%)', { exact: true }).fill('20');
  await page.getByRole('button', { name: 'Generate port grid' }).click();
  // Put the grid inside the image while preserving intentional overlaps.
  await page.getByLabel('First column center (%)', { exact: true }).fill('15');
  await page.getByLabel('Last column center (%)', { exact: true }).fill('85');
  await page.getByRole('button', { name: 'Generate port grid' }).click();
  await review(page).check();
  await page.getByRole('button', { name: 'Save template', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('does not overlap');
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('porttracker.project')!).templates ?? [])).toEqual([]);
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Import template', exact: true })).toBeVisible();
});

