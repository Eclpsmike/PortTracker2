import { seedFacilityLocations } from './facility-location-helpers';
import { test, expect, type Page } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import type { Project } from '../src/project';
const saved = (page: Page): Promise<Project> => page.evaluate(() => JSON.parse(localStorage.getItem('porttracker.project')!));
async function port(page: Page, rack: string, equipment: string, number: number) {
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('combobox', { name: 'Browse rack', exact: true }).selectOption(rack);
  await page.getByRole('combobox', { name: 'Browse equipment', exact: true }).selectOption(equipment);
  await page.getByRole('button', { name: new RegExp(`^Port ${number},`) }).click();
}
async function physical(page: Page, kind = 'fiber') {
  await page.getByText('Physical port settings', { exact: true }).click();
  await page.getByRole('combobox', { name: 'Port type', exact: true }).selectOption(kind);
  if (kind !== 'fiber') await page.getByLabel('Installed transceiver', { exact: true }).fill('Test LC optical module');
  await page.getByRole('combobox', { name: 'Port connector', exact: true }).selectOption('LC');
  await page.getByRole('combobox', { name: 'Port fiber mode', exact: true }).selectOption('single-mode');
  await page.getByLabel('Port strand count', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Save physical port', exact: true }).click();
}

test.beforeEach(async ({ page }) => { await seedFacilityLocations(page, ["Fiber shelf east"]); });

test('fiber connection checks, stock, port metadata, moves and backups work together', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await port(page, 'CAB-A02', 'PP-B01', 24);
  await physical(page);
  await page.getByLabel('Facility location', { exact: true }).selectOption('Fiber shelf east');
  await port(page, 'CAB-A01', 'SW-A01', 48);
  await physical(page, 'sfp-plus');
  await page.getByRole('combobox', { name: 'Port VLAN', exact: true }).selectOption('99');
  await expect(page.locator('[data-port="CAB-A01/SW-A01/48"]')).toHaveAttribute('data-medium', 'fiber');
  await page.getByRole('button', { name: 'Add connection', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Cable medium', exact: true })).toHaveValue('fiber');
  await expect(page.getByRole('combobox', { name: 'To port', exact: true })).toHaveValue('24');
  await page.getByRole('combobox', { name: 'Fiber mode', exact: true }).selectOption('multimode');
  await page.getByRole('button', { name: 'Create connection', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('mode does not match');
  await page.getByRole('combobox', { name: 'Fiber mode', exact: true }).selectOption('single-mode');
  await page.getByRole('button', { name: 'Create connection', exact: true }).click();
  await expect(page.locator('.connection-details')).toContainText('Fiber · Single-mode · LC–LC · 2 strands');
  await expect(page.locator('.estimate-summary')).toContainText('No stock match');
  await page.evaluate(() => { location.hash = '/configuration/stock'; });
  await page.getByRole('button', { name: 'Add fiber stock', exact: true }).click();
  await page.getByLabel('Fiber cable length (m)', { exact: true }).fill('30');
  await page.getByRole('button', { name: 'Save fiber stock', exact: true }).click();
  await expect(page.getByRole('table', { name: 'Available fiber cables' })).toContainText('Single-mode · LC–LC · 2 strands');
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await expect(page.locator('.estimate-summary strong').nth(1)).toContainText('30');
  await port(page, 'CAB-A01', 'SW-A01', 48);
  await page.getByText('Physical port settings', { exact: true }).click();
  await page.getByRole('combobox', { name: 'Port type', exact: true }).selectOption('copper');
  await page.getByRole('button', { name: 'Save physical port', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('requires a copper cable');
  expect((await saved(page)).locations[0].layout.portMedia!['CAB-A01/SW-A01/48'].kind).toBe('sfp-plus');
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('button', { name: 'Move equipment', exact: true }).click();
  await page.getByLabel('Destination rack', { exact: true }).selectOption('CAB-A02');
  await page.getByRole('button', { name: 'Save equipment position', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Equipment', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Manage ports', exact: true }).click();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export', exact: true }).click();
  const backup = await readFile((await (await download).path())!);
  const exported = JSON.parse(backup.toString()) as Project;
  expect(exported.locations[0].layout.portMedia!['CAB-A02/SW-A01/48'].transceiver).toBe('Test LC optical module');
  expect(exported.configuration.fiberStock![0].lengthM).toBe(30);
  expect(exported.locations[0].layout.portDetails!['CAB-A02/PP-B01/24'].facilityLocation).toBe('Fiber shelf east');
  await page.goto('/#/locations');
  await page.getByLabel('Project JSON file').setInputFiles({ name: 'fiber.json', mimeType: 'application/json', buffer: backup });
  await page.getByRole('button', { name: 'Replace with imported project', exact: true }).click();
  await page.getByRole('button', { name: 'Open IDF-01', exact: true }).click();
  await port(page, 'CAB-A02', 'SW-A01', 48);
  await page.getByText('Physical port settings', { exact: true }).click();
  await expect(page.getByLabel('Installed transceiver', { exact: true })).toHaveValue('Test LC optical module');
  expect(errors).toEqual([]);
});

