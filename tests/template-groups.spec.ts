import { test, expect } from '@playwright/test';

for (const mobile of [false, true]) test(`${mobile ? 'mobile' : 'desktop'} maps separate port grids and preserves earlier groups when adding uplinks`, async ({ page }) => {
  if (mobile) await page.setViewportSize({ width: 390, height: 844 });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/#/configuration/templates');
  await page.getByRole('button', { name: 'Import template', exact: true }).click();
  // Optical interfaces deliberately precede copper in the source definition.
  const interfaces = [...Array.from({ length: 4 }, (_, i) => i + 12), ...Array.from({ length: 12 }, (_, i) => i)].map(i => `  - name: ${i < 12 ? `ge-0/0/${i}` : `xe-0/1/${i - 12}`}\n    type: ${i < 12 ? '1000base-t' : '10gbase-x-sfpp'}`).join('\n');
  await page.getByLabel('Device definition YAML').setInputFiles({ name: 'groups.yaml', mimeType: 'text/yaml', buffer: Buffer.from(`manufacturer: Test\nmodel: Grouped switch\nu_height: 1\ninterfaces:\n${interfaces}\n`) });
  await page.getByLabel('Front equipment image', { exact: true }).setInputFiles('public/equipment/netbox/generic-24-port-copper-patch-panel.front.png');
  await page.getByRole('button', { name: 'Continue to port mapping' }).click();
  await page.getByText('Start with a regular grid', { exact: true }).click();
  await page.getByRole('button', { name: 'Clear grid selection', exact: true }).click();
  const generate = page.getByRole('button', { name: 'Generate port grid', exact: true });
  await expect(generate).toBeDisabled();
  await page.getByLabel('First port in range', { exact: true }).selectOption({label:'ge-0/0/0'});
  await page.getByLabel('Last port in range', { exact: true }).selectOption({label:'ge-0/0/11'});
  await page.getByRole('button', { name: 'Select port range', exact: true }).click();
  await page.getByLabel('Grid columns', { exact: true }).fill('6');
  await page.getByLabel('Grid numbering', { exact: true }).selectOption('columns');
  await page.getByLabel('First column center (%)', { exact: true }).fill('5');
  await page.getByLabel('Last column center (%)', { exact: true }).fill('55');
  await page.getByLabel('First row center (%)', { exact: true }).fill('35');
  await page.getByLabel('Last row center (%)', { exact: true }).fill('65');
  await page.getByLabel('Grid socket width (%)', { exact: true }).fill('4');
  await page.getByLabel('Grid socket height (%)', { exact: true }).fill('20');
  await expect(page.locator('[data-grid-preview-port]')).toHaveCount(12);
  await expect(page.getByRole('button', { name: /^Select mapped port / })).toHaveCount(0);
  const stage = page.locator('.template-mapping-preview');
  const field = page.getByLabel('Grid socket height (%)', { exact: true });
  await field.evaluate(e => e.scrollIntoView({ block: 'end' }));
  const stageBox = await stage.boundingBox(), fieldBox = await field.boundingBox();
  expect(stageBox!.y).toBeGreaterThanOrEqual(0);
  expect(stageBox!.y + stageBox!.height).toBeLessThan(fieldBox!.y);
  expect(fieldBox!.y + fieldBox!.height).toBeLessThanOrEqual(page.viewportSize()!.height + 1);
  await page.screenshot({ path: `artifacts/template-grid-${mobile ? 'mobile' : 'desktop'}.png` });
  await generate.click();
  const positions = () => page.locator('.template-map g[role="button"] rect').evaluateAll(nodes => nodes.map(n => ({ x: n.getAttribute('x'), y: n.getAttribute('y'), width: n.getAttribute('width'), height: n.getAttribute('height') })));
  const copper = await positions();
  expect(copper).toHaveLength(12);
  await page.getByRole('button', { name: 'Include more ports', exact: true }).click();
  await page.getByRole('button', { name: 'Include all ports', exact: true }).click();
  await page.getByRole('button', { name: 'Continue to port mapping' }).click();
  await expect(page.locator('.mapping-preview-caption')).toContainText('12 / 16 ports mapped');
  expect(await positions()).toEqual(copper);
  await page.getByText('Start with a regular grid', { exact: true }).click();
  await page.getByRole('button', { name: 'Select unmapped ports', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'Grid port xe-0/1/0 — xe-0/1/0', exact: true })).toBeChecked();
  await expect(page.getByRole('checkbox', { name: 'Grid port ge-0/0/0 — ge-0/0/0', exact: true })).not.toBeChecked();
  await page.getByLabel('Grid columns', { exact: true }).fill('2');
  await page.getByLabel('First column center (%)', { exact: true }).fill('75');
  await page.getByLabel('Last column center (%)', { exact: true }).fill('90');
  await page.getByLabel('First row center (%)', { exact: true }).fill('35');
  await page.getByLabel('Last row center (%)', { exact: true }).fill('65');
  await expect(page.locator('[data-grid-preview-port]')).toHaveCount(4);
  await generate.click();
  expect((await positions()).slice(0, 12)).toEqual(copper);
  const before = await positions();
  await page.getByLabel('Last column center (%)', { exact: true }).fill('92');
  expect(await positions()).toEqual(before);
  await generate.click();
  expect((await positions()).slice(0, 12)).toEqual(copper);
  expect((await positions())[15].x).not.toBe(before[15].x);
  await page.getByLabel('I checked every socket position and numbered interface against the image.').check();
  await page.getByRole('button', { name: 'Save template', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Test Grouped switch', exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Edit template Test Grouped switch', exact: true }).click();
  expect((await positions()).slice(0, 12)).toEqual(copper);
  await expect(page.getByRole('button', { name: /^Select mapped port / })).toHaveCount(16);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
