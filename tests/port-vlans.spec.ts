import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('unconnected port VLANs appear in the rack, protect configuration, and survive a cable lifecycle', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('button', { name: 'Port 24, available', exact: true }).click();
  const control = page.getByRole('combobox', { name: 'Port VLAN', exact: true });
  const socket = page.locator('[data-port="CAB-A01/PP-A04/24"]');
  await expect(control).toHaveValue('');
  await control.selectOption('99');
  await expect(page.locator('.selected-port-controls')).toContainText('Available · no cable assigned');
  await expect(page.locator('.cable-group')).toHaveCount(32);
  await expect(socket).toHaveAttribute('data-vlan', '99');
  await expect(socket.locator('.port-vlan-marker')).toHaveCount(0);
  await page.getByRole('checkbox', { name: 'VLAN 99 — Servers', exact: true }).check();
  await expect(socket.locator('.port-vlan-marker')).toHaveAttribute('stroke', '#8b9cac');
  await expect(page.locator('[data-grid-port="CAB-A01/PP-A04/24"]')).toHaveCSS('border-bottom-color', 'rgb(139, 156, 172)');
  await page.getByRole('checkbox', { name: 'Cables', exact: true }).uncheck();
  await expect(socket.locator('.port-vlan-marker')).toHaveCount(1);
  await page.getByRole('checkbox', { name: 'VLAN colors', exact: true }).uncheck();
  await expect(socket.locator('.port-vlan-marker')).toHaveCount(0);
  await page.getByRole('checkbox', { name: 'VLAN colors', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Cables', exact: true }).check();
  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove VLAN 99', exact: true })).toBeDisabled();
  const row = page.locator('.configuration-table tbody tr').filter({ has: page.getByRole('button', { name: 'Edit VLAN 99', exact: true }) });
  await expect(row.locator('td').nth(3)).toHaveText('1 assigned');
  await expect(row.locator('td').nth(4)).toHaveText('Unused');
  await page.getByRole('link', { name: 'Back to racks', exact: true }).click();
  await expect(control).toHaveValue('99');
  await page.screenshot({ path: 'artifacts/port-vlan-unconnected.png' });
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
  await page.getByRole('button', { name: 'Connect this port', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Logical VLAN' })).toHaveValue('99');
  await page.getByRole('button', { name: 'Create connection', exact: true }).click();
  await expect(page.locator('.connection-details')).toContainText('99 — Servers');
  await page.getByRole('button', { name: 'Edit connection', exact: true }).click();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('button', { name: 'Port 24, available', exact: true }).click();
  await expect(control).toHaveValue('99');
  await expect(page.locator('.cable-group')).toHaveCount(32);
  const pendingDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const download = await pendingDownload;
  const exported = JSON.parse(await readFile((await download.path())!, 'utf8'));
  expect(exported.locations.find((l: { id: string }) => l.id === exported.activeLocationId).layout.portVlans['CAB-A01/PP-A04/24']).toBe(99);
  expect(exported.locations.find((l: { id: string }) => l.id === exported.activeLocationId).layout.cables).toHaveLength(32);
  await control.selectOption('');
  await expect(socket.locator('.port-vlan-marker')).toHaveCount(0);
  await page.getByRole('link', { name: 'Configuration', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Remove VLAN 99', exact: true })).toBeEnabled();
  expect(errors).toEqual([]);
});

test('connected port VLAN changes stay independent and mobile switch ports support assignment', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('button', { name: 'Port 18, connected', exact: true }).click();
  const control = page.getByRole('combobox', { name: 'Port VLAN', exact: true });
  await expect(control).toHaveValue('30');
  await control.selectOption('99');
  await expect(page.locator('.port-vlan-mismatch')).toContainText('Cable VLAN: 30');
  await page.getByRole('button', { name: 'View connection', exact: true }).click();
  await expect(page.locator('.connection-details')).toContainText('30 — Voice');
  await page.getByRole('button', { name: 'Edit connection', exact: true }).click();
  await expect(page.getByRole('dialog').locator('.port-vlan-mismatch')).toBeVisible();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('button', { name: 'Port 18, available', exact: true }).click();
  await expect(control).toHaveValue('99');
  await expect(page.locator('.port-vlan-mismatch')).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('combobox', { name: 'Browse equipment' }).selectOption('SW-A01');
  await page.getByRole('button', { name: 'Port 48, available', exact: true }).click();
  await control.selectOption('60');
  await expect(page.locator('[data-port="CAB-A01/SW-A01/48"]')).toHaveAttribute('data-vlan', '60');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Reset demo', exact: true }).click();
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  await page.getByRole('combobox', { name: 'Browse equipment' }).selectOption('SW-A01');
  await page.getByRole('button', { name: 'Port 48, available', exact: true }).click();
  await expect(control).toHaveValue('');
});
