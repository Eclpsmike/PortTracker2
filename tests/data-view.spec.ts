test('data view filters, sorts, paginates and exports all matching connections without changing rack view', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/#/cabinets');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  const zoom = await page.locator('.zoom-control span').textContent();
  await page.getByRole('link', { name: 'Data view', exact: true }).click();
  await expect(page).toHaveURL(/#\/data$/);
  await expect(page.getByRole('heading', { name: 'Data view', exact: true })).toBeVisible();
  const table = page.getByRole('table');
  await expect(table.locator('tbody tr')).toHaveCount(32);
  await expect(table).not.toContainText('CAB-A01');
  await page.getByRole('combobox', { name: 'Cable VLAN', exact: true }).selectOption('30');
  await expect(table.locator('tbody tr')).toHaveCount(7);
  await page.getByRole('combobox', { name: 'Rack', exact: true }).selectOption('idf-01/CAB-A01');
  await expect(table.locator('tbody tr')).toHaveCount(4);
  await page.getByRole('button', { name: 'Reset filters' }).click();
  await page.getByRole('combobox', { name: 'Rows per page' }).selectOption('25');
  await expect(table.locator('tbody tr')).toHaveCount(25);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(table.locator('tbody tr')).toHaveCount(7);
  await page.getByRole('button', { name: 'Estimated length' }).click();
  const values = await table.locator('.data-cell-estimated').allTextContents();
  const numbers = values.map(Number.parseFloat);
  expect(numbers).toEqual([...numbers].sort((a, b) => a - b));
  await page.getByRole('combobox', { name: 'Length units' }).selectOption('imperial');
  await expect(table.locator('.data-cell-estimated').first()).toContainText('ft');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('porttracker-connections.csv');
  const csv = await readFile((await download.path())!, 'utf8');
  expect(csv).toContain('"Estimated length (ft)"');
  expect(csv.trim().split('\r\n')).toHaveLength(33);
  expect(csv).not.toContain('CAB-A01');
  await page.getByRole('searchbox', { name: 'Search connections' }).fill('no such equipment');
  await expect(table).toContainText('No connections match these filters.');
  await expect(page.getByRole('button', { name: 'Export CSV' })).toBeDisabled();
  await page.getByRole('button', { name: 'Reset filters' }).click();
  await page.screenshot({ path: 'artifacts/data-view-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Racks', exact: true }).click();
  await expect(page.locator('.zoom-control span')).toHaveText(zoom!);
  expect(errors).toEqual([]);
});

test('data view handles frame scope, archived frames, notes and mobile table scrolling', async ({ page }) => {
  const project = defaultProject(defaultConfiguration(), 'metric');
  const source = project.locations[0];
  source.layout.racks[0].label = 'Core rack';
  source.layout.portDetails = { [endpointKey(source.layout.cables[0].from)]: { facilityLocation: 'Room 101', notes: '=SUM(1,2)\n"Check outlet"' } };
  project.configuration.facilityLocations = [{ name: 'Room 101', color: '#123456' }];
  project.locations.push({ ...structuredClone(source), id: 'mdf-02', name: 'MDF-02', type: 'MDF', calibration: { ...source.calibration, slackM: 10 } });
  project.locations.push({ ...structuredClone(source), id: 'idf-old', name: 'Old frame', archived: true });
  await page.addInitScript(data => localStorage.setItem('porttracker.project', JSON.stringify(data)), project);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/data');
  const table = page.getByRole('table');
  await expect(page.locator('.configuration-table-toolbar')).toContainText('32 of 32 connections');
  await page.getByRole('combobox', { name: 'Distribution frame', exact: true }).selectOption('');
  await expect(page.locator('.configuration-table-toolbar')).toContainText('64 of 64 connections');
  await page.getByRole('checkbox', { name: 'Include archived frames' }).check();
  await expect(page.locator('.configuration-table-toolbar')).toContainText('96 of 96 connections');
  await page.getByRole('combobox', { name: 'Distribution frame', exact: true }).selectOption('idf-old');
  await expect(table.locator('.data-cell-frame').first()).toContainText('Old frame (archived)');
  await page.getByRole('checkbox', { name: 'Include archived frames' }).uncheck();
  await expect(page.locator('.configuration-table-toolbar')).toContainText('64 of 64 connections');
  await page.getByRole('combobox', { name: 'Rack', exact: true }).selectOption('mdf-02/CAB-A01');
  await expect(page.locator('.configuration-table-toolbar')).toContainText('17 of 64 connections');
  await page.getByRole('searchbox', { name: 'Search connections' }).fill('Room 101');
  await expect(table.locator('tbody tr')).toHaveCount(1);
  await expect(table).toContainText('MDF-02');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const csv = await readFile((await (await downloadPromise).path())!, 'utf8');
  expect(csv).toContain('"\'=SUM(1,2)\n""Check outlet"""');
  expect(csv).toContain('"Estimated length (m)"');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const scroll = page.getByRole('region', { name: 'Connections table, scroll for more columns' });
  expect(await scroll.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/data-view-mobile.png', fullPage: true });
});

test('rack and port tabs list inventory, retain independent filters, and export all ports', async ({ page }) => {
  await page.goto('/#/data');
  const connections = page.getByRole('tabpanel', { name: 'Connections', exact: true });
  await connections.getByRole('combobox', { name: 'Cable VLAN', exact: true }).selectOption('30');
  await page.getByRole('tab', { name: 'Racks', exact: true }).click();
  const racks = page.getByRole('tabpanel', { name: 'Racks', exact: true });
  await expect(racks.getByRole('status')).toHaveText('2 racks · 50 equipment items');
  await expect(racks.getByRole('table').locator('tbody tr')).toHaveCount(50);
  await expect(racks.getByRole('table')).not.toContainText('CAB-A01');
  await racks.getByRole('combobox', { name: 'Equipment type', exact: true }).selectOption('Switch');
  await expect(racks.getByRole('table').locator('tbody tr')).toHaveCount(10);
  const rackDownload = page.waitForEvent('download');
  await racks.getByRole('button', { name: 'Export CSV' }).click();
  const rackCsv = await readFile((await (await rackDownload).path())!, 'utf8');
  expect(rackCsv.trim().split('\r\n')).toHaveLength(11);
  expect(rackCsv).toContain('"Rack units"');
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  const ports = page.getByRole('tabpanel', { name: 'Ports', exact: true });
  await expect(ports.getByRole('status')).toHaveText('1440 of 1440 ports');
  const downloadPromise = page.waitForEvent('download');
  await ports.getByRole('button', { name: 'Export CSV' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('porttracker-ports.csv');
  const csv = await readFile((await download.path())!, 'utf8');
  expect(csv.trim().split('\r\n')).toHaveLength(1441);
  expect(csv).toContain('"Available"');
  await ports.getByRole('combobox', { name: 'Equipment', exact: true }).selectOption('idf-01/CAB-A01/PP-A02');
  await expect(ports.getByRole('table').locator('tbody tr')).toHaveCount(24);
  await ports.getByRole('combobox', { name: 'Connection status', exact: true }).selectOption('Connected');
  await expect(ports.getByRole('table').locator('tbody tr')).toHaveCount(3);
  await expect(ports.getByRole('table')).toContainText('Rack A / SW-A01 / Port 3');
  await page.screenshot({ path: 'artifacts/data-ports-desktop.png', fullPage: true });
  await page.getByRole('tab', { name: 'Connections', exact: true }).click();
  await expect(connections.getByRole('combobox', { name: 'Cable VLAN', exact: true })).toHaveValue('30');
  await expect(connections.getByRole('table').locator('tbody tr')).toHaveCount(7);
  await page.getByRole('tab', { name: 'Racks', exact: true }).click();
  await expect(racks.getByRole('combobox', { name: 'Equipment type', exact: true })).toHaveValue('Switch');
  await page.getByRole('tab', { name: 'Racks', exact: true }).press('ArrowRight');
  await expect(page.getByRole('tab', { name: 'Ports', exact: true })).toBeFocused();
  await expect(ports.getByRole('combobox', { name: 'Equipment', exact: true })).toHaveValue('idf-01/CAB-A01/PP-A02');
});

test('inventory includes empty racks and unconnected port zero with assignments on mobile', async ({ page }) => {
  const project = defaultProject(defaultConfiguration(), 'metric');
  const frame = project.locations[0];
  frame.layout.racks[0].equipment = frame.layout.racks[0].equipment.filter(e => ['PP-A02', 'SW-A01'].includes(e.id));
  frame.layout.racks[1].equipment = [];
  frame.layout.cables = [frame.layout.cables[0]];
  frame.layout.portVlans = {};
  frame.layout = setEquipmentPortStart(frame.layout, 'CAB-A01', 'PP-A02', 0);
  frame.layout.portVlans = { 'CAB-A01/PP-A02/0': 99 };
  frame.layout.portDetails = { 'CAB-A01/PP-A02/0': { facilityLocation: 'Room 201', notes: 'Spare outlet' } };
  project.configuration.facilityLocations = [{ name: 'Room 201', color: '#123456' }];
  project.locations.push({ ...structuredClone(frame), id: 'other', name: 'Other frame', archived: true });
  await page.addInitScript(data => localStorage.setItem('porttracker.project', JSON.stringify(data)), project);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/data');
  await page.getByRole('tab', { name: 'Racks', exact: true }).click();
  const racks = page.getByRole('tabpanel', { name: 'Racks', exact: true });
  await expect(racks.getByRole('status')).toHaveText('2 racks · 2 equipment items · 1 empty rack');
  await expect(racks.getByRole('table').locator('tbody tr')).toHaveCount(3);
  await expect(racks.getByRole('table')).toContainText('Empty rack');
  await expect(racks.getByRole('table')).toContainText('0–23');
  await page.screenshot({ path: 'artifacts/data-racks-mobile.png', fullPage: true });
  await page.getByRole('tab', { name: 'Ports', exact: true }).click();
  const ports = page.getByRole('tabpanel', { name: 'Ports', exact: true });
  await expect(ports.getByRole('status')).toHaveText('72 of 72 ports');
  await ports.getByRole('combobox', { name: 'Port VLAN', exact: true }).selectOption('99');
  await expect(ports.getByRole('table').locator('tbody tr')).toHaveCount(1);
  await expect(ports.locator('.data-cell-port')).toHaveText('0');
  await expect(ports.getByRole('table')).toContainText('Available');
  await expect(ports.getByRole('table')).toContainText('Spare outlet');
  const downloadPromise = page.waitForEvent('download');
  await ports.getByRole('button', { name: 'Export CSV' }).click();
  const csv = await readFile((await (await downloadPromise).path())!, 'utf8');
  expect(csv).toContain('"0"');
  expect(csv).toContain('"Spare outlet"');
  await ports.getByRole('combobox', { name: 'Distribution frame', exact: true }).selectOption('');
  await ports.getByRole('checkbox', { name: 'Include archived frames' }).check();
  await expect(ports.getByRole('table').locator('tbody tr')).toHaveCount(2);
  await ports.getByRole('combobox', { name: 'Rack', exact: true }).selectOption('other/CAB-A01');
  await expect(ports.getByRole('table').locator('tbody tr')).toHaveCount(1);
  await expect(ports.getByRole('table')).toContainText('Other frame (archived)');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'artifacts/data-ports-mobile.png', fullPage: true });
});
